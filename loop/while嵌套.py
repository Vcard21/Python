"""
 會有好幾層while，會有外層while跟內層while
 跟if一樣
"""
# 外層表白100天，內層每天10支玫瑰花
i = 1
while i <= 100:

    print(f"今天是第{i}天，準備表白")

    # 內層循環的控制變量
    j = 1
    while j <=10:
        print(f"送給小美第{j}支玫瑰花")
        j+=1

    print("小美，我喜歡你")
    i+=1
    # 最後100天時也滿足小於"等於"的條件，所以最後print要設置成 i - 1
print(f"堅持到第{i - 1}天")
# 外層控外層，內層控內層